/// The value type accepted by an option or positional argument.
pub const ValueKind = enum {
    boolean,
    integer,
    float,
    string,
};

/// Behaviour when an option appears more than once.
pub const RepeatPolicy = enum {
    /// Reject a second occurrence.
    reject,
    /// Keep only the last occurrence.
    last_wins,
    /// Keep every occurrence. Use `Parsed.get_all_options` to retrieve them.
    collect,
};

pub const Option = struct {
    long: []const u8,
    short: ?u8 = null,
    help: []const u8 = "",

    /// `null` means a flag that does not consume a value.
    /// `.boolean` means an explicit `true` / `false` value is required.
    kind: ?ValueKind = null,
    metavar: ?[]const u8 = null,

    required: bool = false,
    default: ?[]const u8 = null,
    env: ?[]const u8 = null,

    hidden: bool = false,
    negatable: bool = false,
    repeat: RepeatPolicy = .last_wins,
};

pub const Argument = struct {
    name: []const u8,
    kind: ValueKind = .string,
    help: []const u8 = "",

    required: bool = false,
    variadic: bool = false,
    hidden: bool = false,
};

pub const Example = struct {
    command: []const u8,
    description: []const u8 = "",
};

/// Built-in options are generated by the renderer and handled by the parser.
pub const Builtins = struct {
    help: bool = true,
    version: bool = true,
    color: bool = true,
};

pub const Command = struct {
    name: []const u8,
    description: []const u8 = "",
    version: ?[]const u8 = null,

    options: []const Option = &.{},
    arguments: []const Argument = &.{},
    sub_commands: []const Command = &.{},
    examples: []const Example = &.{},

    builtins: Builtins = .{},
    hidden: bool = false,
};
